/** 取翻译字符串，支持 {n} 占位符替换 */
export function t(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const raw = dicts[locale]?.[key] ?? dicts.en[key] ?? key;
  if (!vars) return raw;
  return Object.entries(vars).reduce((s, [k, v]) => s.replaceAll(`{${k}}`, String(v)), raw);
}
